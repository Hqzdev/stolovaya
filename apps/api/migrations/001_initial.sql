CREATE TYPE order_status AS ENUM ('new', 'cooking', 'ready');
CREATE TYPE employee_role AS ENUM ('admin', 'cook');

CREATE TABLE dishes (id text PRIMARY KEY, name text NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 1 AND 120));
CREATE TABLE school_groups (id text PRIMARY KEY, name text NOT NULL UNIQUE CHECK (length(trim(name)) BETWEEN 1 AND 60));
CREATE TABLE orders (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dish_id text NOT NULL REFERENCES dishes(id),
  group_id text NOT NULL REFERENCES school_groups(id),
  quantity integer NOT NULL CHECK (quantity BETWEEN 1 AND 10000),
  service_date date NOT NULL,
  serving_time time NOT NULL,
  status order_status NOT NULL DEFAULT 'new',
  created_at timestamptz NOT NULL DEFAULT now(),
  cooking_at timestamptz,
  ready_at timestamptz,
  created_by text NOT NULL,
  CHECK ((status = 'new' AND cooking_at IS NULL AND ready_at IS NULL) OR (status = 'cooking' AND cooking_at IS NOT NULL AND ready_at IS NULL) OR (status = 'ready' AND cooking_at IS NOT NULL AND ready_at IS NOT NULL)),
  CHECK (cooking_at IS NULL OR cooking_at >= created_at),
  CHECK (ready_at IS NULL OR ready_at >= cooking_at)
);
CREATE INDEX orders_service_date_idx ON orders(service_date DESC, id DESC);
CREATE INDEX orders_dish_date_idx ON orders(dish_id, service_date);
CREATE INDEX orders_group_date_idx ON orders(group_id, service_date);
CREATE TABLE order_events (
  id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  status order_status NOT NULL,
  happened_at timestamptz NOT NULL DEFAULT now(),
  actor text NOT NULL,
  UNIQUE(order_id, status)
);
CREATE TABLE sessions (
  token_hash text PRIMARY KEY,
  role employee_role NOT NULL,
  credential_version text NOT NULL,
  csrf_token text NOT NULL,
  expires_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX sessions_expiry_idx ON sessions(expires_at);
